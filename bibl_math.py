'''
Programa para utilizar a biblioteca MATH
'''
import math

# Calcula a raiz quadrada de um numero  
print(math.sqrt(16))
# Calcula o seno de um angulo
print(math.sin(45))
# Calcula o cosseno de um angulo
print(math.cos(45))
# Calcula o logaritmo de um numero na base 10
print(math.log(1000,10))
# Imprime o valor de pi
print(math.pi)
# Calcula o fatorial de um numero
print(math.factorial(5))
# Calcula o valor absoluto de um numero
print(math.fabs(-10))
# Calcula o teto de um numero
print(math.ceil(4.2))
# Calcula o piso de um numero
print(math.floor(4.8))
# Calcula a potência de um numero
print(math.pow(2,3))